function countLetters(word) {
  return [...word].length;
}

function dartString(value) {
  return `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
}

function flattenBank() {
  const flattened = new Map();

  for (const [length, groups] of curatedBank.entries()) {
    const items = [];
    for (const group of groups) {
      for (const word of group.words) {
        items.push({ word, category: group.category });
      }
    }
    flattened.set(length, items);
  }

  return flattened;
}

function validateBank() {
  const flattened = flattenBank();

  for (const [length, targetCount] of targets.entries()) {
    const items = flattened.get(length) ?? [];
    const seen = new Set();

    if (items.length !== targetCount) {
      throw new Error(
        `Expected ${targetCount} words for length ${length}, found ${items.length}.`,
      );
    }

    for (const item of items) {
      if (!arabicOnly.test(item.word)) {
        throw new Error(`Invalid Arabic word: ${item.word}`);
      }

      if (countLetters(item.word) !== length) {
        throw new Error(
          `Length mismatch: ${item.word} should be ${length} letters.`,
        );
      }

      if (seen.has(item.word)) {
        throw new Error(`Duplicate word in ${length}-letter bank: ${item.word}`);
      }

      if (blockedWords.has(item.word)) {
        throw new Error(`Blocked word still present: ${item.word}`);
      }

      seen.add(item.word);
    }
  }

  const allWords = new Set(
    [...flattened.values()].flat().map((item) => item.word),
  );

  for (const word of Object.keys(customDefinitions)) {
    if (!allWords.has(word)) {
      throw new Error(`Definition exists for non-bank word: ${word}`);
    }
  }
}

function emitMode(groups) {
  const lines = [];

  for (const group of groups) {
    lines.push(`      ..._category(${dartString(group.category)}, [`);
    for (const word of group.words) {
      lines.push(`        ${dartString(word)},`);
    }
    lines.push('      ]),');
  }

  return lines.join('\n');
}

function emitDefinitions() {
  return Object.entries(customDefinitions)
    .sort(([a], [b]) => a.localeCompare(b, 'ar'))
    .map(([word, definition]) => `    ${dartString(word)}: ${dartString(definition)},`)
    .join('\n');
}

