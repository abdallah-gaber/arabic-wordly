List<ArabicPuzzle> _category(String category, List<String> words) {
  return words
      .map(
        (word) => ArabicPuzzle(
          word: word,
          category: category,
          definition: _definitionForWord(word, category),
        ),
      )
      .toList(growable: false);
}

